%% USER SETTINGS

% Select the anatomical side represented by both meshes. The ERC frame
% convention used by this project points positive z medially for a left
% knee and laterally for a right knee.
kneeSide = "left";

% Move the femoral landmark-ray origin proximally from the femoral ACS
% origin. The default keeps the rays at the original epicondylar-axis location.
femur_epicondyleProximalOffset_mm = 0;

% Rotate both femoral landmark rays toward the local positive x-axis. A zero
% angle preserves the original straight mediolateral landmark definition.
femur_epicondyleAnteriorAngleOffset_deg = 20;

% Move the tibial landmark line this far distally from the tibial ACS
% origin. The mesh and ACS coordinates in this dataset are in millimetres.
tibia_condyleDistalOffset_mm = 10;

% Rotate both tibial landmark rays toward the local positive x-axis, which
% is the anterior direction in the ERC anatomical coordinate system.
tibia_condyleAnteriorAngleOffset_deg = 25;

% Move the center of the femoral shaft band proximally from the femoral ACS
% origin. This places the new surface landmark on the diaphysis rather than
% near the epicondyles.
femur_shaftProximalOffset_mm = 120;

% Rotate the femoral shaft ray about the ACS positive y-axis. Positive
% angles rotate local positive x toward local negative z.
femur_shaftAnteriorAngleOffset_deg = 0;

% Move the center of the tibial shaft band distally from the tibial ACS
% origin. The setting is stored as a positive distance and applied along
% the ACS negative y-axis below.
tibia_shaftDistalOffset_mm = 150;

% Rotate the tibial shaft ray about the ACS positive y-axis using the same
% signed convention as the femoral shaft ray.
tibia_shaftAnteriorAngleOffset_deg = -45;

% Keep the two shaft-cutting planes five millimetres from the band center.
% The resulting band is therefore ten millimetres thick for both bones.
shaftHalfThickness_mm = 5;



%% LOAD AND VALIDATE THE BONE DATA

% Locate the project from this script instead of depending on MATLAB's
% current folder when the user starts the workflow.
scriptFullPath = mfilename('fullpath');
if isempty(scriptFullPath)
    error('bonePreRegistration:ScriptPathUnavailable', ...
          'Run bonePreRegistration_anatomicalLandmark.m as a complete script so its input path can be resolved.');
end
scriptDirectory  = fileparts(scriptFullPath);
toolsDirectory   = fileparts(scriptDirectory);
projectDirectory = fileparts(toolsDirectory);

% Accept either an absolute folder selected by the user or the original
% project-relative folder. Trying the configured folder first avoids adding
% the project path in front of an already absolute Windows path.
configuredCtmatFullPath = fullfile(filepath_ctmat, filename_ctmat);
projectCtmatFullPath = fullfile(projectDirectory, filepath_ctmat, filename_ctmat);
if isfile(configuredCtmatFullPath)
    ctmatFullPath = configuredCtmatFullPath;
elseif isfile(projectCtmatFullPath)
    ctmatFullPath = projectCtmatFullPath;
else
    error('bonePreRegistration:MissingCtMatFile', ...
        ['The configured CT MAT file does not exist at either resolved ', ...
         'location:\n  %s\n  %s'], configuredCtmatFullPath, ...
        projectCtmatFullPath);
end

% Load only the variable needed by this workflow so unrelated saved values
% cannot accidentally replace settings or intermediate variables.
loadedCtData = load(ctmatFullPath, 'bones');
if ~isfield(loadedCtData, 'bones')
    error('bonePreRegistration:MissingBonesVariable', ...
        'The CT MAT file does not contain a variable named bones: %s', ...
        ctmatFullPath);
end
bones = loadedCtData.bones;
if ~isstruct(bones) || numel(bones) ~= 2
    error('bonePreRegistration:InvalidBonesVariable', ...
        'Variable bones must contain exactly the femur and tibia records.');
end

% Select each bone by its saved anatomical code because femur and tibia can
% appear in either array order in different CT MAT files.
[femurBone, femurBoneIndex] = selectBoneRecordByCode( bones, "F", 'Femur');
[tibiaBone, tibiaBoneIndex] = selectBoneRecordByCode( bones, "T", 'Tibia');
validateBoneRecord(femurBone, 'Femur', femurBoneIndex);
validateBoneRecord(tibiaBone, 'Tibia', tibiaBoneIndex);

% Normalize and validate the side setting once so every later label uses
% exactly the same left/right interpretation.
kneeSide = lower(strtrim(convertCharsToStrings(kneeSide)));
if ~isscalar(kneeSide) || ismissing(kneeSide) || ~any(kneeSide == ["left", "right"])
    error('bonePreRegistration:InvalidKneeSide', 'kneeSide must be either "left" or "right".');
end

% The femoral positive y-axis is proximal, so a nonnegative setting moves
% the ray origin upward along that local anatomical direction.
if ~isnumeric(femur_epicondyleProximalOffset_mm) || ...
        ~isscalar(femur_epicondyleProximalOffset_mm) || ...
        ~isreal(femur_epicondyleProximalOffset_mm) || ...
        ~isfinite(femur_epicondyleProximalOffset_mm) || ...
        femur_epicondyleProximalOffset_mm < 0
    error('bonePreRegistration:InvalidFemurProximalOffset', ...
        'femur_epicondyleProximalOffset_mm must be one finite, nonnegative number.');
end

% Keep each femoral ray on its intended signed-z side. Allow zero so the
% new adjustable calculation can exactly reproduce the previous landmarks.
if ~isnumeric(femur_epicondyleAnteriorAngleOffset_deg) || ...
        ~isscalar(femur_epicondyleAnteriorAngleOffset_deg) || ...
        ~isreal(femur_epicondyleAnteriorAngleOffset_deg) || ...
        ~isfinite(femur_epicondyleAnteriorAngleOffset_deg) || ...
        femur_epicondyleAnteriorAngleOffset_deg < 0 || ...
        femur_epicondyleAnteriorAngleOffset_deg >= 90
    error('bonePreRegistration:InvalidFemurAnteriorAngleOffset', ...
        'femur_epicondyleAnteriorAngleOffset_deg must be one finite number in the range [0, 90) degrees.');
end

% A negative offset would move toward the plateau rather than in the
% requested distal direction, so reject it as a user-setting error.
if ~isnumeric(tibia_condyleDistalOffset_mm) || ...
        ~isscalar(tibia_condyleDistalOffset_mm) || ...
        ~isreal(tibia_condyleDistalOffset_mm) || ...
        ~isfinite(tibia_condyleDistalOffset_mm) || ...
        tibia_condyleDistalOffset_mm < 0
    error('bonePreRegistration:InvalidTibiaDistalOffset', ...
        'tibia_condyleDistalOffset_mm must be one finite, nonnegative number.');
end

% Keep the offset below 90 degrees so each ray remains on its intended
% negative-z or positive-z side. Allow zero to reproduce the old z-axis
% landmark definition when a user needs that behavior.
if ~isnumeric(tibia_condyleAnteriorAngleOffset_deg) || ...
        ~isscalar(tibia_condyleAnteriorAngleOffset_deg) || ...
        ~isreal(tibia_condyleAnteriorAngleOffset_deg) || ...
        ~isfinite(tibia_condyleAnteriorAngleOffset_deg) || ...
        tibia_condyleAnteriorAngleOffset_deg < 0 || ...
        tibia_condyleAnteriorAngleOffset_deg >= 90
    error('bonePreRegistration:InvalidTibiaAnteriorAngleOffset', ...
        'tibia_condyleAnteriorAngleOffset_deg must be one finite number in the range [0, 90) degrees.');
end

% The femoral shaft offset is a distance along positive y, so negative or
% nonfinite values would reverse or invalidate the requested direction.
if ~isnumeric(femur_shaftProximalOffset_mm) || ...
        ~isscalar(femur_shaftProximalOffset_mm) || ...
        ~isreal(femur_shaftProximalOffset_mm) || ...
        ~isfinite(femur_shaftProximalOffset_mm) || ...
        femur_shaftProximalOffset_mm < 0
    error('bonePreRegistration:InvalidFemurShaftProximalOffset', ...
        'femur_shaftProximalOffset_mm must be one finite, nonnegative number.');
end

% Allow one complete signed turn while rejecting repeated rotations that
% make the saved user setting harder to interpret.
if ~isnumeric(femur_shaftAnteriorAngleOffset_deg) || ...
        ~isscalar(femur_shaftAnteriorAngleOffset_deg) || ...
        ~isreal(femur_shaftAnteriorAngleOffset_deg) || ...
        ~isfinite(femur_shaftAnteriorAngleOffset_deg) || ...
        femur_shaftAnteriorAngleOffset_deg < -180 || ...
        femur_shaftAnteriorAngleOffset_deg > 180
    error('bonePreRegistration:InvalidFemurShaftAnteriorAngleOffset', ...
        'femur_shaftAnteriorAngleOffset_deg must be one finite number in the range [-180, 180] degrees.');
end

% The tibial setting is also stored as a positive distance even though it
% is applied along negative y to reach the distal shaft.
if ~isnumeric(tibia_shaftDistalOffset_mm) || ...
        ~isscalar(tibia_shaftDistalOffset_mm) || ...
        ~isreal(tibia_shaftDistalOffset_mm) || ...
        ~isfinite(tibia_shaftDistalOffset_mm) || ...
        tibia_shaftDistalOffset_mm < 0
    error('bonePreRegistration:InvalidTibiaShaftDistalOffset', ...
        'tibia_shaftDistalOffset_mm must be one finite, nonnegative number.');
end

% Use the same complete signed-turn limit for both bones so positive and
% negative angles have identical meanings throughout the saved results.
if ~isnumeric(tibia_shaftAnteriorAngleOffset_deg) || ...
        ~isscalar(tibia_shaftAnteriorAngleOffset_deg) || ...
        ~isreal(tibia_shaftAnteriorAngleOffset_deg) || ...
        ~isfinite(tibia_shaftAnteriorAngleOffset_deg) || ...
        tibia_shaftAnteriorAngleOffset_deg < -180 || ...
        tibia_shaftAnteriorAngleOffset_deg > 180
    error('bonePreRegistration:InvalidTibiaShaftAnteriorAngleOffset', ...
        'tibia_shaftAnteriorAngleOffset_deg must be one finite number in the range [-180, 180] degrees.');
end

% This is currently a fixed geometric definition, but validate the named
% value so later edits cannot silently create an empty or inverted band.
if ~isnumeric(shaftHalfThickness_mm) || ...
        ~isscalar(shaftHalfThickness_mm) || ...
        ~isreal(shaftHalfThickness_mm) || ...
        ~isfinite(shaftHalfThickness_mm) || ...
        shaftHalfThickness_mm <= 0
    error('bonePreRegistration:InvalidShaftHalfThickness', ...
        'shaftHalfThickness_mm must be one finite, positive number.');
end



%% FIND THE FEMORAL LANDMARKS

% Add the requested distance along the femoral positive y-axis so the ray
% origin moves proximally from the epicondylar ACS origin.
T_femurBone_CT           = femurBone.T_bone_CT;
point_femurAcsOrigin_CT  = T_femurBone_CT(1:3, 4).';
vector_femurX_CT         = normalizeVector(T_femurBone_CT(1:3, 1).', 'femoral x-axis');
vector_femurY_CT         = normalizeVector(T_femurBone_CT(1:3, 2).', 'femoral y-axis');
vector_femurZ_CT         = normalizeVector(T_femurBone_CT(1:3, 3).', 'femoral z-axis');
point_femurLineOrigin_CT = point_femurAcsOrigin_CT + femur_epicondyleProximalOffset_mm * vector_femurY_CT;

% Rotate both outward z directions toward positive x. These equations keep
% each ray in the femoral xz-plane and work for either knee side because the
% laterality mapping is applied after the signed-z intersections are found.
vector_femurNegativeZRay_CT = normalizeVector( ...
    sind(femur_epicondyleAnteriorAngleOffset_deg) * vector_femurX_CT - ...
    cosd(femur_epicondyleAnteriorAngleOffset_deg) * vector_femurZ_CT, ...
    'femoral negative-z anterior ray');
vector_femurPositiveZRay_CT = normalizeVector( ...
    sind(femur_epicondyleAnteriorAngleOffset_deg) * vector_femurX_CT + ...
    cosd(femur_epicondyleAnteriorAngleOffset_deg) * vector_femurZ_CT, ...
    'femoral positive-z anterior ray');
vectors_femurRayDirections_CT = [vector_femurNegativeZRay_CT; ...
                                 vector_femurPositiveZRay_CT];

% Use the same ordered paired-ray mode as the tibia. The helper records the
% negative-z ray with negative distances and the positive-z ray with
% positive distances, so the existing outer-intersection selector remains
% shared by both bones.
[points_femurIntersections_CT, distances_femurIntersections_mm] = ...
    intersectInfiniteLineWithMesh(femurBone.mesh, ...
    point_femurLineOrigin_CT, vectors_femurRayDirections_CT, 'femur');
[point_femurNegativeZ_CT, point_femurPositiveZ_CT, ...
    distance_femurNegativeZ_mm, distance_femurPositiveZ_mm] = ...
    selectOuterLineIntersections(points_femurIntersections_CT, ...
    distances_femurIntersections_mm, 'femur');

% Build the new femoral shaft point from vertices inside the ten-millimetre
% band centered in the requested proximal direction. A positive signed
% offset tells the helper to move along the femoral ACS positive y-axis.
[point_femurShaft_CT, distance_femurShaft_mm, ...
    diagnostic_femurShaft] = calculateShaftSurfaceLandmark( ...
    femurBone.mesh, T_femurBone_CT, femur_shaftProximalOffset_mm, ...
    shaftHalfThickness_mm, femur_shaftAnteriorAngleOffset_deg, 'femur');



%% FIND THE TIBIAL LANDMARKS

% The ERC positive y-axis is proximal, so subtracting the requested
% distance moves the tibial line origin distally along the condyles.
T_tibiaBone_CT           = tibiaBone.T_bone_CT;
point_tibiaAcsOrigin_CT  = T_tibiaBone_CT(1:3, 4).';
vector_tibiaX_CT         = normalizeVector(T_tibiaBone_CT(1:3, 1).', 'tibial x-axis');
vector_tibiaY_CT         = normalizeVector(T_tibiaBone_CT(1:3, 2).', 'tibial y-axis');
vector_tibiaZ_CT         = normalizeVector(T_tibiaBone_CT(1:3, 3).', 'tibial z-axis');
point_tibiaLineOrigin_CT = point_tibiaAcsOrigin_CT - tibia_condyleDistalOffset_mm * vector_tibiaY_CT;

% Rotate the two outward z directions toward positive x. The first row is
% the negative-z ray after a negative y-axis rotation, and the second row is
% the positive-z ray after a positive y-axis rotation. Both therefore point
% anteriorly while staying in the tibial xz-plane.
vector_tibiaNegativeZRay_CT = normalizeVector( ...
    sind(tibia_condyleAnteriorAngleOffset_deg) * vector_tibiaX_CT - ...
    cosd(tibia_condyleAnteriorAngleOffset_deg) * vector_tibiaZ_CT, ...
    'tibial negative-z anterior ray');
vector_tibiaPositiveZRay_CT = normalizeVector( ...
    sind(tibia_condyleAnteriorAngleOffset_deg) * vector_tibiaX_CT + ...
    cosd(tibia_condyleAnteriorAngleOffset_deg) * vector_tibiaZ_CT, ...
    'tibial positive-z anterior ray');
vectors_tibiaRayDirections_CT = [vector_tibiaNegativeZRay_CT; ...
                                 vector_tibiaPositiveZRay_CT];

% Reuse the exact triangle intersection calculation in its ordered two-ray
% mode. Negative signed distances identify the negative-z ray and positive
% signed distances identify the positive-z ray.
[points_tibiaIntersections_CT, distances_tibiaIntersections_mm] = ...
    intersectInfiniteLineWithMesh(tibiaBone.mesh, ...
    point_tibiaLineOrigin_CT, vectors_tibiaRayDirections_CT, 'tibia');
[point_tibiaNegativeZ_CT, point_tibiaPositiveZ_CT, ...
    distance_tibiaNegativeZ_mm, distance_tibiaPositiveZ_mm] = ...
    selectOuterLineIntersections(points_tibiaIntersections_CT, ...
    distances_tibiaIntersections_mm, 'tibia');

% Negate the user-entered distal distance before passing it to the shared
% helper because the tibial distal direction is the ACS negative y-axis.
[point_tibiaShaft_CT, distance_tibiaShaft_mm, ...
    diagnostic_tibiaShaft] = calculateShaftSurfaceLandmark( ...
    tibiaBone.mesh, T_tibiaBone_CT, -tibia_shaftDistalOffset_mm, ...
    shaftHalfThickness_mm, tibia_shaftAnteriorAngleOffset_deg, 'tibia');



%% MAP THE SIGNED POINTS TO ANATOMICAL SIDES

% Use the selected knee side to give stable anatomical names while keeping
% the underlying signed-z geometry available for inspection.
switch kneeSide
    case "left"
        positiveZSide = "medial";
        point_femurMedial_CT  = point_femurPositiveZ_CT;
        point_femurLateral_CT = point_femurNegativeZ_CT;
        point_tibiaMedial_CT  = point_tibiaPositiveZ_CT;
        point_tibiaLateral_CT = point_tibiaNegativeZ_CT;
    case "right"
        positiveZSide = "lateral";
        point_femurMedial_CT  = point_femurNegativeZ_CT;
        point_femurLateral_CT = point_femurPositiveZ_CT;
        point_tibiaMedial_CT  = point_tibiaNegativeZ_CT;
        point_tibiaLateral_CT = point_tibiaPositiveZ_CT;
end



%% COLLECT AND REPORT THE LANDMARK RESULTS

