landmarks(femurBoneIndex).anteriorAngleOffset_deg = femur_epicondyleAnteriorAngleOffset_deg;
landmarks(femurBoneIndex).shaftProximalOffset_mm = femur_shaftProximalOffset_mm;
landmarks(femurBoneIndex).shaftDistalOffset_mm = 0;
landmarks(femurBoneIndex).shaftAnteriorAngleOffset_deg = femur_shaftAnteriorAngleOffset_deg;
landmarks(femurBoneIndex).medial = point_femurMedial_CT;
landmarks(femurBoneIndex).lateral = point_femurLateral_CT;
landmarks(femurBoneIndex).shaft = point_femurShaft_CT;
landmarks(femurBoneIndex).points = [point_femurMedial_CT; ...
                                         point_femurLateral_CT; ...
                                         point_femurShaft_CT];
landmarks(tibiaBoneIndex).distalOffset_mm = tibia_condyleDistalOffset_mm;
landmarks(tibiaBoneIndex).proximalOffset_mm = 0;
landmarks(tibiaBoneIndex).anteriorAngleOffset_deg = tibia_condyleAnteriorAngleOffset_deg;
landmarks(tibiaBoneIndex).shaftProximalOffset_mm = 0;
landmarks(tibiaBoneIndex).shaftDistalOffset_mm = tibia_shaftDistalOffset_mm;
landmarks(tibiaBoneIndex).shaftAnteriorAngleOffset_deg = tibia_shaftAnteriorAngleOffset_deg;
landmarks(tibiaBoneIndex).medial = point_tibiaMedial_CT;
landmarks(tibiaBoneIndex).lateral = point_tibiaLateral_CT;
landmarks(tibiaBoneIndex).shaft = point_tibiaShaft_CT;
landmarks(tibiaBoneIndex).points = [point_tibiaMedial_CT; ...
                                        point_tibiaLateral_CT; ...
                                        point_tibiaShaft_CT];

% Build a matching diagnostics array without duplicating either bone mesh.
% These fields retain every unique crossing for later topology inspection.
emptyShaftDiagnostic = struct( ...
    'signedOffset_mm', 0, ...
    'halfThickness_mm', shaftHalfThickness_mm, ...
    'planePoints', zeros(2, 3), ...
    'planeNormal', zeros(1, 3), ...
    'retainedVertexIndices', zeros(0, 1), ...
    'retainedVertexCount', 0, ...
    'centroid', zeros(1, 3), ...
    'anteriorAngleOffset_deg', 0, ...
    'lineDirection', zeros(1, 3), ...
    'points', zeros(0, 3), ...
    'signedDistances_mm', zeros(0, 1), ...
    'selectedDistance_mm', 0, ...
    'selectedPoint', zeros(1, 3));
diagnosticTemplate = struct( ...
    'name', '', ...
    'bone', '', ...
    'T_bone_CT', eye(4), ...
