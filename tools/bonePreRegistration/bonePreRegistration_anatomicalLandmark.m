intersectionDiagnostics(femurBoneIndex).distalOffset_mm = 0;
intersectionDiagnostics(femurBoneIndex).proximalOffset_mm = femur_epicondyleProximalOffset_mm;
intersectionDiagnostics(femurBoneIndex).anteriorAngleOffset_deg = femur_epicondyleAnteriorAngleOffset_deg;
intersectionDiagnostics(femurBoneIndex).lineOrigin = point_femurLineOrigin_CT;
intersectionDiagnostics(femurBoneIndex).lineDirection = vectors_femurRayDirections_CT;
