    'coordinateFrame', "CT", ...
    'units', "mm", ...
    'kneeSide', kneeSide, ...
    'positiveZSide', positiveZSide, ...
    'distalOffset_mm', 0, ...
    'proximalOffset_mm', 0, ...
    'anteriorAngleOffset_deg', 0, ...
    'shaftProximalOffset_mm', 0, ...
    'shaftDistalOffset_mm', 0, ...
    'shaftAnteriorAngleOffset_deg', 0, ...
    'shaftHalfThickness_mm', shaftHalfThickness_mm, ...
    'medial', zeros(1, 3), ...
    'lateral', zeros(1, 3), ...
    'shaft', zeros(1, 3), ...
    'pointLabels', ["medial"; "lateral"; "shaft"], ...
    'points', zeros(3, 3));
landmarks = repmat(landmarkTemplate, size(bones));

