function [boneRecord, boneIndex] = selectBoneRecordByCode( ...
        bones, requestedCode, boneLabel)
%SELECTBONERECORDBYCODE Find one anatomical bone without assuming its index.
%   Different MAT files can save femur and tibia in different array orders.
%   This helper uses the bones(...).bone indicator so the correct mesh and
%   transform are selected regardless of that order.
%
%   Inputs:
%       bones         - Struct array containing the saved bone records.
%       requestedCode - One-character indicator, such as "F" or "T".
%       boneLabel     - Human-readable anatomical name for error messages.
%
%   Outputs:
%       boneRecord - The single record matching requestedCode.
%       boneIndex  - Its one-based index in the original bones array.

% Require the indicator before reading individual records so a legacy MAT
% file fails with a direct explanation.
if ~isfield(bones, 'bone')
    error('bonePreRegistration:MissingBoneCodeField', ...
        'Every record in bones must contain the field bone.');
end

% Normalize each saved indicator independently because MAT files may store
% the values as either character vectors or string scalars.
boneCodes = strings(size(bones));
for currentIndex = 1:numel(bones)
    currentCode = convertCharsToStrings(bones(currentIndex).bone);
    if ~isscalar(currentCode) || ismissing(currentCode) || ...
            strlength(strtrim(currentCode)) == 0
        error('bonePreRegistration:InvalidBoneCode', ...
            'bones(%d).bone must contain one valid bone indicator.', ...
            currentIndex);
    end
    boneCodes(currentIndex) = upper(strtrim(currentCode));
end

% Exactly one match is required because no safe automatic choice exists
% when a requested bone is absent or duplicated.
requestedCode = upper(strtrim(convertCharsToStrings(requestedCode)));
matchingIndices = find(boneCodes == requestedCode);
if numel(matchingIndices) ~= 1
    error('bonePreRegistration:BoneCodeNotUnique', ...
        ['Expected exactly one %s record with bones(...).bone == "%s", ', ...
         'but found %d.'], boneLabel, requestedCode, numel(matchingIndices));
end

% Return both the selected record and its source index for later validation
% messages and workspace diagnostics.
boneIndex = matchingIndices(1);
boneRecord = bones(boneIndex);
end

function validateBoneRecord(boneRecord, expectedName, boneIndex)
%VALIDATEBONERECORD Check one saved bone record before landmark extraction.
%   This function verifies the mesh and anatomical transform because an
%   invalid record would otherwise produce misleading surface landmarks.
%
%   Inputs:
%       boneRecord   - Scalar struct containing name, mesh, and T_bone_CT.
%       expectedName - Expected anatomical name, such as 'Femur'.
%       boneIndex    - Selected one-based position inside the bones array.
%
%   Outputs:
%       None. The function throws a descriptive error when validation fails.

% Require one struct with every field used by the extraction workflow.
if ~isstruct(boneRecord) || ~isscalar(boneRecord) || ...
        ~all(isfield(boneRecord, {'name', 'mesh', 'T_bone_CT'}))
    error('bonePreRegistration:InvalidBoneRecord', ...
        'bones(%d) must contain name, mesh, and T_bone_CT.', boneIndex);
end

% Confirm that the selected code and descriptive name refer to the same
% anatomy rather than silently accepting inconsistent saved metadata.
recordName = convertCharsToStrings(boneRecord.name);
if ~isscalar(recordName) || ismissing(recordName) || ...
        ~strcmpi(strtrim(recordName), expectedName)
    error('bonePreRegistration:UnexpectedBoneName', ...
        'Expected bones(%d) to be %s, but found "%s".', ...
        boneIndex, expectedName, recordName);
end

% A triangulation supplies the triangle connectivity required by the exact
% line-surface calculation.
meshTri = boneRecord.mesh;
if ~isa(meshTri, 'triangulation') || isempty(meshTri.Points) || ...
        isempty(meshTri.ConnectivityList)
    error('bonePreRegistration:InvalidBoneMesh', ...
        'The %s mesh must be a nonempty MATLAB triangulation.', expectedName);
end
if any(~isfinite(meshTri.Points), 'all')
    error('bonePreRegistration:NonFiniteBoneMesh', ...
        'The %s mesh contains NaN or Inf vertex coordinates.', expectedName);
end

% Check the complete homogeneous transform before reading individual axes.
T_bone_CT = boneRecord.T_bone_CT;
if ~isnumeric(T_bone_CT) || ~isreal(T_bone_CT) || ...
        ~isequal(size(T_bone_CT), [4, 4]) || ...
        any(~isfinite(T_bone_CT), 'all')
    error('bonePreRegistration:InvalidBoneTransform', ...
        'The %s T_bone_CT must be one finite real 4-by-4 matrix.', ...
        expectedName);
end
if norm(T_bone_CT(4, :) - [0, 0, 0, 1], inf) > 1e-9
    error('bonePreRegistration:InvalidHomogeneousRow', ...
        'The %s T_bone_CT must end with [0 0 0 1].', expectedName);
end

% Require a proper near-orthonormal rotation so z-sign and distal y-shifts
% keep their intended anatomical meaning.
rotationMatrix = T_bone_CT(1:3, 1:3);
if norm(rotationMatrix.' * rotationMatrix - eye(3), 'fro') > 1e-3 || ...
        abs(det(rotationMatrix) - 1) > 1e-3
    error('bonePreRegistration:InvalidBoneRotation', ...
        'The %s rotation in T_bone_CT must be right-handed and orthonormal.', ...
        expectedName);
end
end

function unitVector = normalizeVector(inputVector, vectorLabel)
%NORMALIZEVECTOR Convert a finite 3D direction to unit length.
%   Normalization makes signed intersection parameters represent physical
%   distances and prevents small rotation-matrix scale errors from mattering.
%
%   Inputs:
%       inputVector - Three-element numeric row or column direction.
%       vectorLabel - Human-readable name used in validation errors.
%
%   Outputs:
%       unitVector - One-by-three normalized direction vector.

% Convert every input to a row so later vectorized mesh operations have a
% consistent shape.
inputVector = inputVector(:).';
if numel(inputVector) ~= 3 || ~isreal(inputVector) || ...
        any(~isfinite(inputVector))
    error('bonePreRegistration:InvalidAxisDirection', ...
        'The %s must contain three finite real values.', vectorLabel);
end

% Reject a direction with no usable length before dividing by it.
vectorLength = norm(inputVector);
if vectorLength <= eps(max(1, max(abs(inputVector))))
    error('bonePreRegistration:ZeroAxisDirection', ...
        'The %s has zero or negligible length.', vectorLabel);
end
unitVector = inputVector / vectorLength;
end

function [shaftPoint, selectedDistance_mm, shaftDiagnostic] = ...
        calculateShaftSurfaceLandmark(meshTri, T_bone_CT, ...
        signedOffset_mm, halfThickness_mm, anteriorAngleOffset_deg, ...
        meshLabel)
%CALCULATESHAFTSURFACELANDMARK Find one ACS-directed shaft surface point.
%   The helper selects original mesh vertices inside an ACS y-aligned band,
%   averages those vertices to obtain the requested centroid, and casts a
%   rotated local positive-x line from that centroid. It is needed to place
%   a repeatable diaphysis landmark on either the femur or tibia surface.
%
%   Inputs:
%       meshTri                - MATLAB triangulation of the bone surface in
%                                CT coordinates.
%       T_bone_CT              - Four-by-four transform from the bone ACS to
%                                CT coordinates.
%       signedOffset_mm        - Signed ACS y-coordinate of the band center;
%                                positive is proximal and negative is distal.
%       halfThickness_mm       - Positive distance from the band center to
%                                each of the two cutting planes.
%       anteriorAngleOffset_deg - Signed rotation from ACS positive x about
%                                 ACS positive y, in degrees.
%       meshLabel              - Human-readable bone name used in messages.
%
%   Outputs:
%       shaftPoint         - One-by-three selected surface point in CT.
%       selectedDistance_mm - Positive distance from the centroid to the
%                             selected surface point, in millimetres.
%       shaftDiagnostic    - Structure containing the band definition,
%                            retained vertices, centroid, line, all surface
%                            crossings, and selected result.

% Read and normalize the ACS basis so projection values and line distances
% retain their intended millimetre units despite small transform noise.
acsOrigin_CT = T_bone_CT(1:3, 4).';
acsX_CT = normalizeVector(T_bone_CT(1:3, 1).', ...
    sprintf('%s shaft x-axis', meshLabel));
acsY_CT = normalizeVector(T_bone_CT(1:3, 2).', ...
    sprintf('%s shaft y-axis', meshLabel));
acsZ_CT = normalizeVector(T_bone_CT(1:3, 3).', ...
    sprintf('%s shaft z-axis', meshLabel));

% Define the lower and upper band limits in the bone ACS. Both matching CT
% plane points use positive y as their shared normal, as requested.
lowerPlaneY_mm = signedOffset_mm - halfThickness_mm;
upperPlaneY_mm = signedOffset_mm + halfThickness_mm;
planePoints_CT = [acsOrigin_CT + lowerPlaneY_mm * acsY_CT; ...
                  acsOrigin_CT + upperPlaneY_mm * acsY_CT];

% Project every original surface vertex onto the ACS y-axis. A scale-aware
% tolerance includes vertices that lie numerically on either cutting plane.
vertices_CT = meshTri.Points;
meshExtent_mm = max(vertices_CT, [], 1) - min(vertices_CT, [], 1);
meshScale_mm = max(meshExtent_mm);
planeTolerance_mm = max(1e-9, 1e-9 * meshScale_mm);
vertexY_mm = (vertices_CT - acsOrigin_CT) * acsY_CT.';
isVertexInsideShaftBand = ...
    vertexY_mm >= lowerPlaneY_mm - planeTolerance_mm & ...
    vertexY_mm <= upperPlaneY_mm + planeTolerance_mm;
retainedVertexIndices = find(isVertexInsideShaftBand);

% At least three source vertices are required for a meaningful surface-band
% centroid. A sparse or empty selection usually means the offset is outside
% the available bone mesh.
if numel(retainedVertexIndices) < 3
    error('bonePreRegistration:EmptyShaftBand', ...
        ['The %s shaft band from %.3f to %.3f mm on its ACS y-axis ', ...
         'contains fewer than three mesh vertices. Change the shaft offset ', ...
         'or check the anatomical transform.'], ...
        meshLabel, lowerPlaneY_mm, upperPlaneY_mm);
end

% Use the requested arithmetic mean of original mesh vertices. This choice
% intentionally follows the mesh sampling density rather than surface area
% or enclosed volume.
shaftCentroid_CT = mean(vertices_CT(retainedVertexIndices, :), 1);
if any(~isfinite(shaftCentroid_CT))
    error('bonePreRegistration:InvalidShaftCentroid', ...
        'The %s shaft vertex centroid contains NaN or Inf.', meshLabel);
end

% A right-handed rotation about positive y sends positive x toward negative
% z for a positive angle. The result stays in the ACS x-z plane, so the ray
% cannot leave the selected band through either cutting plane.
shaftLineDirection_CT = normalizeVector( ...
    cosd(anteriorAngleOffset_deg) * acsX_CT - ...
    sind(anteriorAngleOffset_deg) * acsZ_CT, ...
    sprintf('%s shaft landmark direction', meshLabel));

% Find all exact crossings of the full bone surface. Intersecting the full
% mesh avoids creating artificial cap triangles at the two cutting planes.
[shaftIntersectionPoints_CT, shaftSignedDistances_mm] = ...
    intersectInfiniteLineWithMesh(meshTri, shaftCentroid_CT, ...
    shaftLineDirection_CT, sprintf('%s shaft', meshLabel));

% Ignore numerical hits at the centroid before separating the two halves
% of the line. A valid interior centroid must have crossings in front and
% behind it on a closed surface.
sideTolerance_mm = max(1e-9, ...
    1e-9 * max(abs(shaftSignedDistances_mm)));
negativeIntersectionIndices = find( ...
    shaftSignedDistances_mm < -sideTolerance_mm);
positiveIntersectionIndices = find( ...
    shaftSignedDistances_mm > sideTolerance_mm);
if isempty(positiveIntersectionIndices)
    error('bonePreRegistration:NoForwardShaftIntersection', ...
        ['The %s shaft ray has no forward surface crossing. Check the ACS, ', ...
         'shaft offset, and angle setting.'], meshLabel);
end
if isempty(negativeIntersectionIndices)
    error('bonePreRegistration:ShaftCentroidNotEnclosed', ...
        ['The %s shaft centroid has no surface crossing behind the requested ', ...
         'ray. The selected vertex centroid is not safely enclosed.'], ...
        meshLabel);
end

% Each half-line from a point inside a closed surface crosses the boundary
% an odd number of times. This parity guard prevents an outside centroid
% from selecting an entry point as though it were the requested exit point.
hasOddNegativeParity = mod(numel(negativeIntersectionIndices), 2) == 1;
hasOddPositiveParity = mod(numel(positiveIntersectionIndices), 2) == 1;
if ~hasOddNegativeParity || ~hasOddPositiveParity
    error('bonePreRegistration:ShaftCentroidNotEnclosed', ...
        ['The %s shaft line has even crossing parity on at least one side ', ...
         'of its centroid. Check that the mesh is closed and that the ', ...
         'selected vertex centroid lies inside it.'], meshLabel);
end

% The intersection helper sorts signed distances, so the first positive
% entry is the nearest forward exit instead of a farther surface crossing.
selectedIntersectionIndex = positiveIntersectionIndices(1);
shaftPoint = shaftIntersectionPoints_CT(selectedIntersectionIndex, :);
selectedDistance_mm = ...
    shaftSignedDistances_mm(selectedIntersectionIndex);

% Confirm the returned point still obeys the defining line equation. This
% catches accidental sorting or point-distance misalignment immediately.
reconstructedShaftPoint_CT = shaftCentroid_CT + ...
    selectedDistance_mm * shaftLineDirection_CT;
pointTolerance_mm = max(1e-8, 1e-8 * meshScale_mm);
if norm(shaftPoint - reconstructedShaftPoint_CT) > pointTolerance_mm
    error('bonePreRegistration:InconsistentShaftIntersection', ...
        'The %s shaft point does not match its centroid, direction, and distance.', ...
        meshLabel);
end

% Confirm the result remains between the cutting planes. The line direction
% should make this invariant exact apart from floating-point roundoff.
shaftPointY_mm = dot(shaftPoint - acsOrigin_CT, acsY_CT);
if shaftPointY_mm < lowerPlaneY_mm - planeTolerance_mm || ...
        shaftPointY_mm > upperPlaneY_mm + planeTolerance_mm
    error('bonePreRegistration:ShaftPointOutsideBand', ...
        'The %s shaft point lies outside its two cutting planes.', meshLabel);
end

% Keep the complete geometric trail so the saved result can be checked or
% displayed later without repeating the mesh-line intersection calculation.
shaftDiagnostic = struct( ...
    'signedOffset_mm', signedOffset_mm, ...
    'halfThickness_mm', halfThickness_mm, ...
    'planePoints', planePoints_CT, ...
    'planeNormal', acsY_CT, ...
    'retainedVertexIndices', retainedVertexIndices, ...
    'retainedVertexCount', numel(retainedVertexIndices), ...
    'centroid', shaftCentroid_CT, ...
    'anteriorAngleOffset_deg', anteriorAngleOffset_deg, ...
    'lineDirection', shaftLineDirection_CT, ...
    'points', shaftIntersectionPoints_CT, ...
    'signedDistances_mm', shaftSignedDistances_mm, ...
    'selectedDistance_mm', selectedDistance_mm, ...
    'selectedPoint', shaftPoint);
end

function [intersectionPoints, signedDistances] = ...
        intersectInfiniteLineWithMesh(meshTri, lineOrigin, ...
        lineDirection, meshLabel)
%INTERSECTINFINITELINEWITHMESH Find exact line or paired-ray mesh crossings.
%   A one-row direction applies the vectorized Moller-Trumbore test to one
%   infinite line. A two-row direction applies the same test to the ordered
%   negative-z and positive-z outward rays. The paired-ray mode is needed so
%   either bone's landmarks can move anteriorly without incorrectly joining
%   them with one straight line.
%
%   Inputs:
%       meshTri      - MATLAB triangulation describing the bone surface.
%       lineOrigin   - One-by-three common origin in CT coordinates.
%       lineDirection - Either one three-element infinite-line direction or
%                       a two-by-three matrix ordered as negative-z outward
%                       ray followed by positive-z outward ray.
%       meshLabel    - Human-readable bone name used in error messages.
%
%   Outputs:
%       intersectionPoints - N-by-3 unique CT-space surface crossings,
%                            sorted by their signed branch distances.
%       signedDistances    - N-by-1 distances from lineOrigin. In paired-ray
%                            mode, negative values mark the negative-z ray.

% Read all triangle corners once so the intersection calculation stays
% vectorized across the complete mesh.
vertices = meshTri.Points;
faces = meshTri.ConnectivityList;
trianglePoint0 = vertices(faces(:, 1), :);
triangleEdge1 = vertices(faces(:, 2), :) - trianglePoint0;
triangleEdge2 = vertices(faces(:, 3), :) - trianglePoint0;

% Validate the common origin before subtracting it from every triangle.
lineOrigin = lineOrigin(:).';
if ~isnumeric(lineOrigin) || numel(lineOrigin) ~= 3 || ...
        ~isreal(lineOrigin) || any(~isfinite(lineOrigin))
    error('bonePreRegistration:InvalidLineOrigin', ...
        'The %s landmark origin must contain three finite real values.', ...
        meshLabel);
end

% A single row keeps the original infinite-line behavior. Two rows enable
% ordered bone rays without adding a separate intersection algorithm.
if ~isnumeric(lineDirection) || ~isreal(lineDirection) || ...
        any(~isfinite(lineDirection), 'all')
    error('bonePreRegistration:InvalidLineDirection', ...
        'The %s landmark direction must contain finite real values.', ...
        meshLabel);
end
isSingleInfiniteLine = isvector(lineDirection) && numel(lineDirection) == 3;
isOrderedRayPair = isequal(size(lineDirection), [2, 3]);
if ~isSingleInfiniteLine && ~isOrderedRayPair
    error('bonePreRegistration:InvalidLineDirectionShape', ...
        ['The %s landmark direction must be one three-element direction ', ...
         'or a two-by-three ordered ray pair.'], meshLabel);
end

% Normalize every direction so the intersection parameters retain the mesh
% unit of millimetres even when a transform has small scale errors.
if isSingleInfiniteLine
    normalizedDirections = normalizeVector(lineDirection, ...
        sprintf('%s landmark line direction', meshLabel));
else
    normalizedDirections = zeros(2, 3);
    normalizedDirections(1, :) = normalizeVector(lineDirection(1, :), ...
        sprintf('%s negative-z landmark ray', meshLabel));
    normalizedDirections(2, :) = normalizeVector(lineDirection(2, :), ...
        sprintf('%s positive-z landmark ray', meshLabel));
end

% Scale the parallel and duplicate tolerances to the current bone rather
% than assuming every input mesh has the same physical dimensions.
meshExtent = max(vertices, [], 1) - min(vertices, [], 1);
meshScale = max(meshExtent);
if ~isfinite(meshScale) || meshScale <= 0
    error('bonePreRegistration:DegenerateBoneMesh', ...
        'The %s mesh has no usable spatial extent.', meshLabel);
end
parallelTolerance = max(eps(meshScale ^ 2), 1e-12 * meshScale ^ 2);
barycentricTolerance = 1e-10;
mergeTolerance = max(1e-9, 1e-9 * meshScale);
forwardRayTolerance = mergeTolerance;

% The origin-to-triangle vectors do not depend on the chosen direction, so
% calculate them once before processing the line or the two rays.
vectorPoint0ToOrigin = lineOrigin - trianglePoint0;
crossOriginEdge1 = cross(vectorPoint0ToOrigin, triangleEdge1, 2);
intersectionPoints = zeros(0, 3);
signedDistances = zeros(0, 1);

% Run the same vectorized triangle test for the single line or for each of
% the two ordered ray directions.
for directionIndex = 1:size(normalizedDirections, 1)
    currentDirection = normalizedDirections(directionIndex, :);
    repeatedDirection = repmat(currentDirection, size(faces, 1), 1);

    % Skip triangles that are parallel to the current direction because
    % their determinant cannot produce a reliable intersection parameter.
    crossDirectionEdge2 = cross(repeatedDirection, triangleEdge2, 2);
    determinant = sum(triangleEdge1 .* crossDirectionEdge2, 2);
    validTriangle = abs(determinant) > parallelTolerance;

    % Use NaN for invalid faces so they cannot accidentally pass the final
    % barycentric hit test after the valid faces have been calculated.
    uCoordinate = nan(size(determinant));
    vCoordinate = nan(size(determinant));
    signedParameter = nan(size(determinant));
    inverseDeterminant = 1 ./ determinant(validTriangle);

    % Calculate both barycentric coordinates and the distance along the
    % current direction for every nonparallel triangle.
    uCoordinate(validTriangle) = sum( ...
        vectorPoint0ToOrigin(validTriangle, :) .* ...
        crossDirectionEdge2(validTriangle, :), 2) .* inverseDeterminant;
    vCoordinate(validTriangle) = sum( ...
        repeatedDirection(validTriangle, :) .* ...
        crossOriginEdge1(validTriangle, :), 2) .* inverseDeterminant;
    signedParameter(validTriangle) = sum( ...
        triangleEdge2(validTriangle, :) .* ...
        crossOriginEdge1(validTriangle, :), 2) .* inverseDeterminant;

    % Accept triangle-boundary points within a small tolerance so shared
    % edges are found before their duplicate distances are merged.
    isIntersection = validTriangle & ...
        uCoordinate >= -barycentricTolerance & ...
        vCoordinate >= -barycentricTolerance & ...
        (uCoordinate + vCoordinate) <= 1 + barycentricTolerance & ...
        isfinite(signedParameter);
    rawDirectionDistances = signedParameter(isIntersection);

    if isSingleInfiniteLine
        % An infinite line accepts hits on both sides of its origin. Retain
        % this mode for callers that still supply one direction.
        if isempty(rawDirectionDistances)
            error('bonePreRegistration:NoLineMeshIntersection', ...
                ['The %s landmark line does not intersect the mesh. Check ', ...
                 'the ACS and its configured offset settings.'], ...
                meshLabel);
        end
        signedDistances = uniquetol(rawDirectionDistances, ...
            mergeTolerance, 'DataScale', 1);
        signedDistances = sort(signedDistances(:));
        intersectionPoints = lineOrigin + ...
            signedDistances .* currentDirection;
        return;
    end

    % Each bone direction is an outward ray, so discard intersections
    % behind its shared origin and numerical hits directly at that origin.
    forwardDistances = rawDirectionDistances( ...
        rawDirectionDistances > forwardRayTolerance);
    if isempty(forwardDistances)
        raySideNames = {'negative-z', 'positive-z'};
        error('bonePreRegistration:NoRayMeshIntersection', ...
            ['The %s %s landmark ray does not intersect the mesh in its ', ...
             'forward direction. Check the ACS and reduce the configured ', ...
             'linear or anterior angle offset.'], ...
            meshLabel, raySideNames{directionIndex});
    end

    % Merge duplicate triangle hits within this ray before recording their
    % exact points. The first ray receives negative diagnostic distances so
    % the existing negative-z/positive-z selection remains usable.
    forwardDistances = uniquetol(forwardDistances, mergeTolerance, ...
        'DataScale', 1);
    forwardDistances = sort(forwardDistances(:));
    currentPoints = lineOrigin + forwardDistances .* currentDirection;
    if directionIndex == 1
        currentSignedDistances = -forwardDistances;
    else
        currentSignedDistances = forwardDistances;
    end
    intersectionPoints = [intersectionPoints; currentPoints]; %#ok<AGROW>
    signedDistances = [signedDistances; currentSignedDistances]; %#ok<AGROW>
end

% Sort the combined ray results so the first and last entries remain the
% outer negative-z and positive-z crossings used by the existing selector.
[signedDistances, sortedIndices] = sort(signedDistances);
intersectionPoints = intersectionPoints(sortedIndices, :);
end

function [negativePoint, positivePoint, negativeDistance, ...
        positiveDistance] = selectOuterLineIntersections( ...
        intersectionPoints, signedDistances, meshLabel)
%SELECTOUTERLINEINTERSECTIONS Choose exterior crossings on both line sides.
%   Complex or imperfect meshes can cross one line more than twice. The
%   farthest negative and positive crossings consistently represent the two
%   exterior condyle or epicondyle surfaces requested by this workflow.
%
%   Inputs:
%       intersectionPoints - N-by-3 unique points sorted along the line.
%       signedDistances    - N-by-1 matching signed line distances.
%       meshLabel          - Human-readable bone name for error messages.
%
%   Outputs:
%       negativePoint    - One-by-three outer point in negative z.
%       positivePoint    - One-by-three outer point in positive z.
%       negativeDistance - Signed distance of negativePoint from the origin.
%       positiveDistance - Signed distance of positivePoint from the origin.

% Ignore numerical zero when separating the two anatomical line sides.
sideTolerance = max(1e-9, 1e-9 * max(abs(signedDistances)));
negativeIndices = find(signedDistances < -sideTolerance);
positiveIndices = find(signedDistances > sideTolerance);
if isempty(negativeIndices) || isempty(positiveIndices)
    error('bonePreRegistration:MissingOppositeSideIntersections', ...
        ['The %s landmark line must cross the mesh on both sides of its ', ...
         'origin. Check the ACS and reduce that bone''s linear or anterior ', ...
         'angle offset.'], ...
        meshLabel);
end

% The sorted list makes its first and last entries the two exterior points.
negativeIndex = negativeIndices(1);
positiveIndex = positiveIndices(end);
negativePoint = intersectionPoints(negativeIndex, :);
positivePoint = intersectionPoints(positiveIndex, :);
negativeDistance = signedDistances(negativeIndex);
positiveDistance = signedDistances(positiveIndex);
end
