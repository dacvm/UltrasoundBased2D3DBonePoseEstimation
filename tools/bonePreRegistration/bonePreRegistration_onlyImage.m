clear; clc; close all;

%% PATH DEFINITION

% Point to the folder containing the two bone meshes from the same CT scan.
filepath_boneDirectory = 'D:/Documents/BELANDA/SonoSkin/data/CTdata-KneePhantom/NoStudyDescription/meshes/bones';
filename_boneFemur     = 'Femur_1_Smoothed_Reduced.stl';
filename_boneTibia     = 'Tibia_1_Smoothed_Reduced.stl';

% Point to the locally cloned MSK-STAPLE repository.
filepath_mskSTAPLE = 'D:\Documents\BELANDA\SonoSkin\codes\matlab\msk-STAPLE';

%% USER SETTINGS

% Select the anatomical side represented by both meshes.
% Accepted values are 'left', 'l', 'right', or 'r'.
kneeSide = 'left';

% Enable MSK-STAPLE intermediate figures only when troubleshooting its
% tibial plateau extraction. The final verification figure is always shown.
showMskStapleDebugPlots = false;

%% PREPARE MSK-STAPLE AND LOAD THE MESHES

% Add only the MATLAB toolbox tree because this workflow does not use the
% OpenSim model-building functions located elsewhere in the repository.
filepath_stapleMatlab = fullfile(filepath_mskSTAPLE, 'STAPLE');
if ~isfolder(filepath_stapleMatlab)
    error('bonePreRegistration:MissingMskStaple', ...
        'The MSK-STAPLE MATLAB folder does not exist: %s', filepath_stapleMatlab);
end
addpath(genpath(filepath_stapleMatlab));

% Let MSK-STAPLE validate and normalize the user-facing side setting.
% The returned sign is +1 for a right knee and -1 for a left knee.
[sideSign, sideCode] = bodySide2Sign(kneeSide);

% Build the complete mesh paths before loading so missing inputs produce a
% clear error that names the exact file.
filepath_femurStl = fullfile(filepath_boneDirectory, filename_boneFemur);
filepath_tibiaStl = fullfile(filepath_boneDirectory, filename_boneTibia);
if ~isfile(filepath_femurStl)
    error('bonePreRegistration:MissingFemurMesh', ...
        'The femur STL file does not exist: %s', filepath_femurStl);
end
if ~isfile(filepath_tibiaStl)
    error('bonePreRegistration:MissingTibiaMesh', ...
        'The tibia STL file does not exist: %s', filepath_tibiaStl);
end

% Use MSK-STAPLE's loader so face normals are corrected in the same way as
% in its published morphology workflows.
femurTri = load_mesh(filepath_femurStl);
tibiaTri = load_mesh(filepath_tibiaStl);
validateBoneMesh(femurTri, 'femur');
validateBoneMesh(tibiaTri, 'tibia');

%% EXTRACT THE PROXIMAL TIBIAL ARTICULAR SURFACES

% The complete GIBOC tibia call normally uses the ankle to define the
% whole-bone coordinate system. This tibia is truncated, so only the
% extracted proximal plateau surfaces and their local medial/lateral labels
% are used below; ankle-related results are deliberately ignored.
[tibiaBCS, tibiaJCS, tibiaBoneLandmarks, tibiaArticularSurfaces, tibiaAux] = ...
    GIBOC_tibia(tibiaTri, sideCode, 'centroids', false, ...
    showMskStapleDebugPlots, true);

% Select the side-specific field names generated by MSK-STAPLE.
field_plateauMedial = sprintf('plateau_med_%s', sideCode);
field_plateauLateral = sprintf('plateau_lat_%s', sideCode);
if ~isfield(tibiaArticularSurfaces, field_plateauMedial) || ...
        ~isfield(tibiaArticularSurfaces, field_plateauLateral)
    error('bonePreRegistration:MissingTibialPlateaus', ...
        ['MSK-STAPLE did not return the expected %s and %s surfaces. ', ...
        'Inspect its debug plots before using any landmarks.'], ...
        field_plateauMedial, field_plateauLateral);
end

% Read the two plateau meshes and reject empty extraction results before
% calculating any anatomical points from them.
plateauMedialTri = tibiaArticularSurfaces.(field_plateauMedial);
plateauLateralTri = tibiaArticularSurfaces.(field_plateauLateral);
validateBoneMesh(plateauMedialTri, 'medial tibial plateau');
validateBoneMesh(plateauLateralTri, 'lateral tibial plateau');

% Use MSK-STAPLE's area-weighted surface calculation for the medial and
% lateral plateau centers.
plateauMedialProperties = TriMesh2DProperties(plateauMedialTri);
plateauLateralProperties = TriMesh2DProperties(plateauLateralTri);
point_tibiaMedialPlateauCenter = plateauMedialProperties.Center;
point_tibiaLateralPlateauCenter = plateauLateralProperties.Center;

% Define an anatomical medial-to-lateral direction directly from the two
% plateau centers. This direction is independent of the missing ankle.
vector_tibiaMedialToLateral = normalizeVector( ...
    point_tibiaLateralPlateauCenter - point_tibiaMedialPlateauCenter, ...
    'tibial medial-to-lateral direction');

% Report surface extrema as a second tibial condyle definition. These are
% points on the extracted articular meshes, unlike the area centroids.
point_tibiaMedialCondyleOuter = findSurfaceExtreme( ...
    plateauMedialTri, vector_tibiaMedialToLateral, 'minimum');
point_tibiaLateralCondyleOuter = findSurfaceExtreme( ...
    plateauLateralTri, vector_tibiaMedialToLateral, 'maximum');

%% IDENTIFY THE FEMORAL EPICONDYLES ON THE TRUNCATED FEMUR

% Obtain the remaining femoral shaft direction and volume center using an
% MSK-STAPLE inertia calculation. For this elongated partial mesh, the first
% principal direction follows the shaft.
[femurPrincipalAxes, femurCenterVolume, femurInertiaMatrix] = ...
    TriInertiaPpties(femurTri);
vector_femurLong = femurPrincipalAxes(:, 1);

% Point the longitudinal axis proximally. The femur and tibia share one CT
% frame, so the femur volume center lies away from the knee relative to the
% midpoint of the two tibial plateau centers.
point_tibiaKneeCenter = 0.5 * (point_tibiaMedialPlateauCenter + ...
    point_tibiaLateralPlateauCenter);
vector_kneeToFemur = femurCenterVolume(:) - point_tibiaKneeCenter(:);
if dot(vector_femurLong, vector_kneeToFemur) < 0
    vector_femurLong = -vector_femurLong;
end
vector_femurProximal = normalizeVector(vector_femurLong(:), ...
    'femoral proximal direction');

% Transfer the plateau mediolateral direction to the femur, then remove its
% small longitudinal component so the local frame is orthogonal.
vector_femurLateral = vector_tibiaMedialToLateral(:) - ...
    dot(vector_tibiaMedialToLateral(:), vector_femurProximal) * ...
    vector_femurProximal;
vector_femurLateral = normalizeVector(vector_femurLateral, ...
    'femoral lateral direction');

% MSK-STAPLE uses a side-dependent Z direction: lateral for a right knee
% and medial for a left knee. This convention lets landmarkBoneGeom choose
% the correct side-specific extrema for both knees.
vector_femurZ = sideSign * vector_femurLateral;
vector_femurX = normalizeVector(cross(vector_femurProximal, vector_femurZ), ...
    'femoral anterior-posterior direction');
vector_femurZ = normalizeVector(cross(vector_femurX, vector_femurProximal), ...
    'orthogonal femoral medial-lateral direction');

% Assemble the minimum coordinate-system fields required by
% landmarkBoneGeom. The origin is placed at the local knee center for clear
% plotting, while CenterVol is used internally to transform the mesh.
femurLocalBCS.CenterVol = femurCenterVolume(:);
femurLocalBCS.Origin = point_tibiaKneeCenter(:);
femurLocalBCS.InertiaMatrix = femurInertiaMatrix;
femurLocalBCS.V = [vector_femurX, vector_femurProximal, vector_femurZ];

% Ask MSK-STAPLE to locate its standard femoral knee surface landmarks.
% Its trochanter result is intentionally ignored because this mesh does not
% contain the proximal femur.
femurLandmarksMsk = landmarkBoneGeom( ...
    femurTri, femurLocalBCS, sprintf('femur_%s', sideCode));

% Map the side-specific MSK-STAPLE names to stable descriptive field names.
if sideCode == 'r'
    field_femurLateral = 'RKNE';
    field_femurMedial = 'RMFC';
else
    field_femurLateral = 'LKNE';
    field_femurMedial = 'LMFC';
end
point_femurLateralEpicondyle = femurLandmarksMsk.(field_femurLateral)(:).';
point_femurMedialEpicondyle = femurLandmarksMsk.(field_femurMedial)(:).';

%% COLLECT AND CHECK THE LANDMARK RESULTS

% Keep descriptive names so later scripts do not need to understand the
% abbreviated marker names used internally by MSK-STAPLE.
landmarks.kneeSide = sideCode;
landmarks.units = 'mm';
landmarks.femur.medialEpicondyle = point_femurMedialEpicondyle;
landmarks.femur.lateralEpicondyle = point_femurLateralEpicondyle;
landmarks.tibia.medialPlateauCentroid = point_tibiaMedialPlateauCenter;
landmarks.tibia.lateralPlateauCentroid = point_tibiaLateralPlateauCenter;
landmarks.tibia.medialCondyleOuter = point_tibiaMedialCondyleOuter;
landmarks.tibia.lateralCondyleOuter = point_tibiaLateralCondyleOuter;

% Reject coincident or non-finite pairs because they indicate a failed
% surface extraction or an invalid coordinate frame.
validateLandmarkPair(landmarks.femur.medialEpicondyle, ...
    landmarks.femur.lateralEpicondyle, 'femoral epicondyles');
validateLandmarkPair(landmarks.tibia.medialPlateauCentroid, ...
    landmarks.tibia.lateralPlateauCentroid, 'tibial plateau centroids');
validateLandmarkPair(landmarks.tibia.medialCondyleOuter, ...
    landmarks.tibia.lateralCondyleOuter, 'tibial outer condyle points');

% Retain the relevant intermediate values in the workspace so a failed or
% questionable result can be inspected without rerunning the slow analysis.
diagnostics.tibiaBCS = tibiaBCS;
diagnostics.tibiaJCS = tibiaJCS;
diagnostics.tibiaBoneLandmarks = tibiaBoneLandmarks;
diagnostics.tibiaArticularSurfaces = tibiaArticularSurfaces;
diagnostics.tibiaAux = tibiaAux;
diagnostics.femurLocalBCS = femurLocalBCS;
diagnostics.femurLandmarksMsk = femurLandmarksMsk;
diagnostics.plateauMedialProperties = plateauMedialProperties;
diagnostics.plateauLateralProperties = plateauLateralProperties;

% Print all requested coordinates and widths in millimetres for a quick
% numerical review alongside the visual review below.
landmarkNames = ["Femur medial epicondyle"; ...
    "Femur lateral epicondyle"; ...
    "Tibia medial plateau centroid"; ...
    "Tibia lateral plateau centroid"; ...
    "Tibia medial outer condyle"; ...
    "Tibia lateral outer condyle"];
landmarkCoordinates = [landmarks.femur.medialEpicondyle; ...
    landmarks.femur.lateralEpicondyle; ...
    landmarks.tibia.medialPlateauCentroid; ...
    landmarks.tibia.lateralPlateauCentroid; ...
    landmarks.tibia.medialCondyleOuter; ...
    landmarks.tibia.lateralCondyleOuter];
landmarkTable = table(landmarkNames, landmarkCoordinates(:, 1), ...
    landmarkCoordinates(:, 2), landmarkCoordinates(:, 3), ...
    'VariableNames', {'Landmark', 'X_mm', 'Y_mm', 'Z_mm'});
disp(landmarkTable);

fprintf('Femoral epicondylar width: %.2f mm\n', norm( ...
    landmarks.femur.lateralEpicondyle - landmarks.femur.medialEpicondyle));
fprintf('Tibial plateau-centroid separation: %.2f mm\n', norm( ...
    landmarks.tibia.lateralPlateauCentroid - landmarks.tibia.medialPlateauCentroid));
fprintf('Tibial outer-condyle width: %.2f mm\n', norm( ...
    landmarks.tibia.lateralCondyleOuter - landmarks.tibia.medialCondyleOuter));

