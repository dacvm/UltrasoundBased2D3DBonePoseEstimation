%% LOCAL VALIDATION HELPERS

function validateBoneMesh(meshTri, meshLabel)
%VALIDATEBONEMESH Confirm that a triangulated bone or surface can be used.
%   This validation stops the landmark workflow early when an STL or an
%   MSK-STAPLE extraction is empty or contains unusable numeric values.
%
%   Inputs:
%       meshTri   - MATLAB triangulation object to validate.
%       meshLabel - Human-readable name used in an error message.
%
%   Outputs:
%       None. The function throws an error when validation fails.

% Require a triangulation because downstream MSK-STAPLE functions use its
% Points, ConnectivityList, normals, and nearest-neighbor methods.
if ~isa(meshTri, 'triangulation')
    error('bonePreRegistration:InvalidMeshType', ...
        'The %s must be a MATLAB triangulation object.', meshLabel);
end

% Empty vertices or faces indicate that loading or surface extraction did
% not identify a usable anatomical region.
if isempty(meshTri.Points) || isempty(meshTri.ConnectivityList)
    error('bonePreRegistration:EmptyMesh', ...
        'The %s triangulation is empty.', meshLabel);
end

% Non-finite coordinates would make extrema and fitted directions invalid.
if any(~isfinite(meshTri.Points), 'all')
    error('bonePreRegistration:NonFiniteMesh', ...
        'The %s contains NaN or Inf vertex coordinates.', meshLabel);
end
end

function unitVector = normalizeVector(inputVector, vectorLabel)
%NORMALIZEVECTOR Convert a nonzero three-dimensional vector to unit length.
%   Normalizing all anatomical directions keeps projections and cross
%   products comparable and prevents scale from affecting landmark choice.
%
%   Inputs:
%       inputVector - Three-element numeric direction vector.
%       vectorLabel - Human-readable name used in an error message.
%
%   Outputs:
%       unitVector - Three-by-one normalized direction vector.

% Convert row inputs to one consistent column representation.
inputVector = inputVector(:);

% Reject missing, invalid, or nearly zero directions before division.
vectorLength = norm(inputVector);
if numel(inputVector) ~= 3 || ~all(isfinite(inputVector)) || ...
        vectorLength <= eps(max(1, vectorLength))
    error('bonePreRegistration:InvalidDirection', ...
        'Could not determine a valid %s.', vectorLabel);
end

% Divide once after validation to preserve the intended direction.
unitVector = inputVector / vectorLength;
end

function extremePoint = findSurfaceExtreme(surfaceTri, directionVector, operation)
%FINDSURFACEEXTREME Select an outer point from an articular surface mesh.
%   The function projects every surface vertex onto an anatomical direction
%   and returns the vertex at the requested minimum or maximum. A mesh
%   vertex is returned so the result always lies on the extracted surface.
%
%   Inputs:
%       surfaceTri     - Triangulation of one tibial plateau surface.
%       directionVector - Three-element medial-to-lateral unit direction.
%       operation      - Either 'minimum' or 'maximum'.
%
%   Outputs:
%       extremePoint - One-by-three coordinates of the selected vertex.

% Project all vertices along the requested anatomical direction.
projectedPositions = surfaceTri.Points * directionVector(:);

% Select the requested outward end while rejecting unsupported operation
% names that could silently reverse the anatomical meaning.
switch operation
    case 'minimum'
        [~, pointIndex] = min(projectedPositions);
    case 'maximum'
        [~, pointIndex] = max(projectedPositions);
    otherwise
        error('bonePreRegistration:InvalidExtremeOperation', ...
            'Surface extreme operation must be ''minimum'' or ''maximum''.');
end

% Return the original mesh vertex rather than an off-surface projection.
extremePoint = surfaceTri.Points(pointIndex, :);
end

function validateLandmarkPair(pointMedial, pointLateral, pairLabel)
%VALIDATELANDMARKPAIR Check that an anatomical landmark pair is usable.
%   Each landmark must contain one finite XYZ coordinate, and the medial
%   and lateral points must not collapse to the same position.
%
%   Inputs:
%       pointMedial  - Three-element medial landmark coordinate.
%       pointLateral - Three-element lateral landmark coordinate.
%       pairLabel    - Human-readable pair name used in an error message.
%
%   Outputs:
%       None. The function throws an error when validation fails.

% Enforce the same small public contract for every reported point pair.
if numel(pointMedial) ~= 3 || numel(pointLateral) ~= 3 || ...
        any(~isfinite(pointMedial)) || any(~isfinite(pointLateral))
    error('bonePreRegistration:InvalidLandmarkPair', ...
        'The %s must contain two finite XYZ points.', pairLabel);
end

% Coincident points cannot define a mediolateral anatomical direction.
if norm(pointLateral(:) - pointMedial(:)) <= eps
    error('bonePreRegistration:CoincidentLandmarks', ...
        'The medial and lateral %s points are coincident.', pairLabel);
end
end
